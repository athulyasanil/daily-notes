# ==================================================
# OPEN ANY PAGE — /page/1 TO /page/10
# ==================================================
@app.route("/page/<int:page_no>")
def show_page(page_no):

    if page_no < 1 or page_no > len(PAGES):
        abort(404)

    return render_template(
        "index.html",
        page=PAGES[page_no - 1],
        page_no=page_no,
        total=len(PAGES),
        first=(page_no == 1),
        last=(page_no == len(PAGES))
    )


